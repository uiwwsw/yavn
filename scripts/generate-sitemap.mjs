/**
 * Writes public/sitemap.xml from the game manifest, so the list of indexed addresses can
 * never drift from the list of games that actually ship.
 *
 * Two things the hand-maintained file got wrong and this one cannot:
 *  - live2dtest is a rendering fixture, not a story (see story-catalog.mjs), and the 404 page
 *    already excludes it from the library links; it has no business in a sitemap either.
 *  - /, /en/, /create/ and /en/create/ are translations of each other. Listing them as four
 *    unrelated addresses asks search engines to pick a winner. The xhtml:link alternates say
 *    which page is which language, matching the hreflang tags in each page's head.
 *
 * Run from prebuild, after generate-game-list-manifest.mjs, so vite copies the result.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { isStory } from './story-catalog.mjs';

const DEFAULT_ORIGIN = 'https://yavn.vercel.app';

const esc = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

/** A page that exists in both languages: one <url> each, both naming the whole set. */
function translatedPair({ origin, ko, en, changefreq, priority }) {
  const alternates = [
    `    <xhtml:link rel="alternate" hreflang="ko" href="${esc(origin + ko)}"/>`,
    `    <xhtml:link rel="alternate" hreflang="en" href="${esc(origin + en)}"/>`,
    `    <xhtml:link rel="alternate" hreflang="x-default" href="${esc(origin + en)}"/>`,
  ].join('\n');
  return [ko, en]
    .map(
      (loc) => `  <url>
    <loc>${esc(origin + loc)}</loc>
${alternates}
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`,
    )
    .join('\n');
}

export function renderSitemap({ games = [], origin = DEFAULT_ORIGIN } = {}) {
  const sections = [
    translatedPair({ origin, ko: '/', en: '/en/', changefreq: 'weekly', priority: '1.0' }),
    translatedPair({ origin, ko: '/create/', en: '/en/create/', changefreq: 'monthly', priority: '0.7' }),
    ...games.map(
      (game) => `  <url>
    <loc>${esc(origin + game.path)}</loc>
    <changefreq>weekly</changefreq>
    <priority>0.8</priority>
  </url>`,
    ),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs. Edit that script, not this file. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sections.join('\n')}
</urlset>
`;
}

export function selectIndexableGames(games) {
  return games.filter((game) => isStory(game) && game?.path);
}

export async function generateSitemap({ workspaceRoot = process.cwd(), origin } = {}) {
  const manifestPath = path.join(workspaceRoot, 'public', 'game-list', 'index.json');
  const { games = [] } = JSON.parse(await readFile(manifestPath, 'utf8'));
  const indexable = selectIndexableGames(games);
  const xml = renderSitemap({ games: indexable, origin: origin ?? process.env.SITE_ORIGIN ?? DEFAULT_ORIGIN });
  await writeFile(path.join(workspaceRoot, 'public', 'sitemap.xml'), xml, 'utf8');
  return { games: indexable.length, skipped: games.length - indexable.length };
}

const invoked = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : undefined;
if (invoked === import.meta.url) {
  const { games, skipped } = await generateSitemap({});
  console.log(`sitemap.xml written with ${games} story URL(s); ${skipped} not a story.`);
}
